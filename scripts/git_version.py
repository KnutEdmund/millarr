"""PlatformIO pre-build script: write the short git hash into src/fw_version.h.

The header is git-ignored and only rewritten when the hash changes, so a new
commit recompiles just the files that include it (not the whole tree, as a
CPPDEFINES entry would).
"""
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env["PROJECT_DIR"]
dst_path = os.path.join(project_dir, "src", "fw_version.h")


def git(*args):
    return subprocess.check_output(["git", *args], cwd=project_dir, stderr=subprocess.DEVNULL).decode().strip()


try:
    version = git("rev-parse", "--short", "HEAD")
    if git("status", "--porcelain", "--untracked-files=no"):
        version += "-dirty"
except Exception:  # not a git checkout, or git missing
    version = "unknown"

out = (
    "// Generated by scripts/git_version.py. Do not edit.\n"
    "#pragma once\n"
    f'#define FW_GIT_HASH "{version}"\n'
)
existing = None
if os.path.exists(dst_path):
    with open(dst_path, encoding="utf-8") as f:
        existing = f.read()
if existing != out:
    with open(dst_path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"git_version.py: FW_GIT_HASH={version}")
