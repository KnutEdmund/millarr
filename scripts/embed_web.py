"""PlatformIO pre-build script: embed web/index.html into src/web_page.h.

The page is stored as a raw string literal in PROGMEM so the firmware needs no
filesystem image. Regenerated only when the content changes, to keep incremental
builds fast.
"""
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env["PROJECT_DIR"]
src_path = os.path.join(project_dir, "web", "index.html")
dst_path = os.path.join(project_dir, "src", "web_page.h")

with open(src_path, encoding="utf-8") as f:
    html = f.read()

DELIM = "html"
if f'){DELIM}"' in html:
    raise SystemExit(f"embed_web.py: index.html must not contain '){DELIM}\"'")

out = (
    "// Generated by scripts/embed_web.py from web/index.html. Do not edit.\n"
    "#pragma once\n"
    "#include <pgmspace.h>\n"
    f'static const char INDEX_HTML[] PROGMEM = R"{DELIM}({html}){DELIM}";\n'
)

existing = None
if os.path.exists(dst_path):
    with open(dst_path, encoding="utf-8") as f:
        existing = f.read()

if existing != out:
    with open(dst_path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"embed_web.py: regenerated {os.path.relpath(dst_path, project_dir)}")
